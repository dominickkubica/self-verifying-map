"""Example plugin: the extractors options-scanner's map is built with.

An app-specific plugin can import the app, which the kit's generic extractors never do:
tables come from running the real migrations into a scratch database, routes from the
FastAPI routers themselves, jobs from the schedule function. Generic parts (module
docstrings, the SQL scan, import following) come from the kit. In options-scanner,
`map/config.json` is:

    {"extractors": [{"type": "plugin", "factory": "map_extractors:extractors"}]}

It runs only inside that repository; it is here to show what a stack-specific plugin
looks like. The output it produces is in `examples/generated/`.
"""

from __future__ import annotations

import ast
import importlib
import inspect
import pkgutil
import re
import tempfile
from collections import defaultdict
from dataclasses import dataclass
from functools import cache
from pathlib import Path

import optscan.api.routers as routers_package
from fastapi.routing import APIRoute
from optscan.config import REPO_ROOT, Settings
from optscan.jobs.schedule import jobs
from optscan.storage import db

from lean_agent_kit.repomap import Extractor, Item, ModulesExtractor, SqlExtractor
from lean_agent_kit.repomap.core import table
from lean_agent_kit.repomap.pysource import Imports, group_calls

SRC = REPO_ROOT / "src" / "optscan"
FRONTEND = REPO_ROOT / "frontend" / "src"
VIEWS = FRONTEND / "views"
API_CLIENT = FRONTEND / "api.js"

#: The prefix every API route is mounted under, left off the paths written here the
#: same way the dashboard's client leaves it off.
API_PREFIX = "/api"

HEADER = (
    "<!-- Generated by `optscan map generate` from the code. Do not edit by hand: the "
    "map test fails on any difference. -->\n\n"
)

#: Imports that say nothing about wiring: wire formats, domain types, settings, logging.
QUIET_IMPORTS = (
    "optscan.api.schemas",
    "optscan.models",
    "optscan.config",
    "optscan.logging",
)

IMPORTS = Imports("optscan", SRC, QUIET_IMPORTS)


class Modules(ModulesExtractor):
    header = HEADER

    def __init__(self) -> None:
        super().__init__(SRC, "src/optscan")

    def render(self, items, gaps):
        groups: dict[str, list[list[str]]] = defaultdict(list)
        for item in items:
            groups[item.group].append(item.row)
        parts = [f"# Modules\n\n{self.intro}\n"]
        for package in sorted(groups, key=lambda name: (name != "(top level)", name)):
            parts.append(f"\n## {package}\n\n" + table(self.columns, groups[package]))
        return "".join(parts)


def _tables() -> list[str]:
    """Every table the migrations create, from a scratch database."""
    with (
        tempfile.TemporaryDirectory() as folder,
        db.session(Path(folder) / "map.sqlite") as conn,
    ):
        return sorted(
            row[0]
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
            )
        )


class Storage(SqlExtractor):
    header = HEADER

    def __init__(self) -> None:
        super().__init__(SRC, _tables(), "src/optscan")

    def render(self, items, gaps):
        return (
            "# Storage\n\nEvery table the migrations create, with the modules whose SQL writes "
            "it and reads it. Found by scanning string literals for INSERT, UPDATE, DELETE, "
            "REPLACE, FROM and JOIN against the table names.\n\n"
            + table(self.columns, [item.row for item in items])
            + "\n## SQL the scanner could not resolve\n\nA table name built at run time. "
            "Listed so the gap is visible; the map test caps how many there may be.\n\n"
            + ("\n".join(f"- {line}" for line in self.unresolved) or "None.")
            + "\n"
        )


# ---- routes, caches and the dashboard -----------------------------------------------


@dataclass
class _Route:
    path: str
    methods: set[str]
    router: str
    uses: set[str]


def _routes() -> dict[str, _Route]:
    package = routers_package
    routes: dict[str, _Route] = {}
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda i: i.name):
        module = importlib.import_module(f"{package.__name__}.{info.name}")
        router = getattr(module, "router", None)
        if router is None:
            continue
        tree = ast.parse(inspect.getsource(module))
        for route in router.routes:
            if not isinstance(route, APIRoute):
                continue
            entry = routes.setdefault(
                route.path, _Route(route.path, set(), f"api/routers/{info.name}.py", set())
            )
            entry.methods |= set(route.methods)
            entry.uses |= IMPORTS.reach(tree, route.endpoint.__name__)
    return routes


def _caches() -> list[list[str]]:
    path = SRC / "api" / "deps.py"
    tree = ast.parse(path.read_text(encoding="utf-8"))
    constants = {
        node.targets[0].id: ast.unparse(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name)
    }
    caches = {
        node.targets[0].id: ast.unparse(node.value.args[0]) if node.value.args else ""
        for node in tree.body
        if isinstance(node, ast.Assign)
        and isinstance(node.value, ast.Call)
        and isinstance(node.value.func, ast.Name)
        and node.value.func.id == "_TimedCache"
    }
    put_in: dict[str, set[str]] = defaultdict(set)
    ttls: dict[str, set[str]] = defaultdict(set)
    cleared: dict[str, set[str]] = defaultdict(set)
    for function in tree.body:
        if not isinstance(function, ast.FunctionDef):
            continue
        ttl_names = {
            node.id
            for node in ast.walk(function)
            if isinstance(node, ast.Name) and node.id.endswith("_TTL_SECONDS")
        }
        for node in ast.walk(function):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id in caches
            ):
                name = node.func.value.id
                if node.func.attr == "put":
                    put_in[name].add(function.name)
                    ttls[name] |= {f"{n} = {constants.get(n, '?')} s" for n in ttl_names}
                elif node.func.attr == "clear":
                    cleared[name].add(function.name)
    return [
        [
            f"`{name}`",
            caches[name],
            ", ".join(sorted(ttls[name])) or "none (until replaced)",
            ", ".join(f"`{n}`" for n in sorted(put_in[name])) or "-",
            ", ".join(f"`{n}`" for n in sorted(cleared[name])) or "-",
        ]
        for name in sorted(caches)
    ]


def _template_path(text: str, start: int) -> str:
    """Read a string or template literal from `start` (its opening quote), as a path.

    `${query(...)}` drops out and any other `${...}` becomes `{}`, so the result
    compares with a route path whose parameters are normalised the same way.
    """
    quote = text[start]
    index, path = start + 1, ""
    while index < len(text) and text[index] != quote:
        if text.startswith("${", index):
            depth, end = 1, index + 2
            while depth:
                depth += {"{": 1, "}": -1}.get(text[end], 0)
                end += 1
            inner = text[index + 2 : end - 1]
            if inner != "BASE" and not inner.startswith("query("):
                path += "{}"
            index = end
            continue
        path += text[index]
        index += 1
    return path


def _client() -> dict[str, tuple[str, str]]:
    """The dashboard's API client: function name -> (method, normalised path)."""
    text = API_CLIENT.read_text(encoding="utf-8")
    body = text[text.index("export const api = {") :]
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"^  (\w+): ", body, re.M)]
    functions = {}
    for index, (offset, name) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(body)
        entry = body[offset:end]
        literal = re.search(r"[`\"](?=/|\$\{BASE\}/)", entry)
        if literal is None:
            continue
        method = re.search(r"method:\s*\"(\w+)\"", entry)
        functions[name] = (
            method.group(1) if method else "GET",
            _template_path(entry, literal.start()),
        )
    return functions


def _normalise(path: str) -> str:
    return re.sub(r"\{[^}]*\}", "{}", path)


#: `api.chain(` and the chained form `api\n  .chain(`; never the `./api.js` import path.
_CLIENT_CALL = re.compile(r"(?<![\w/.])api\s*\.\s*(\w+)")
#: A route reached without the client, such as the EventSource in live.js.
_DIRECT = re.compile(r"[\"`]" + API_PREFIX + r"(/[^\"`$?]*)")
DIRECT_PREFIX = "fetch "


def _callers() -> dict[str, list[str]]:
    """Each frontend file that calls the API -> the client functions it calls.

    A route fetched directly, without the client, appears as `fetch /path`.
    """
    out = {}
    for path in sorted(FRONTEND.rglob("*")):
        if path.suffix not in (".js", ".jsx") or path == API_CLIENT:
            continue
        source = path.read_text(encoding="utf-8")
        names = sorted(
            set(_CLIENT_CALL.findall(source))
            | {DIRECT_PREFIX + direct for direct in _DIRECT.findall(source)}
        )
        relative = path.relative_to(FRONTEND).with_suffix("").as_posix()
        name = relative.removeprefix("views/")
        if names or path.parent == VIEWS:
            out[name] = names
    return out


@cache
def _dashboard():
    """Routes, callers and the client, read once for the routes and views files."""
    routes, callers, client = _routes(), _callers(), _client()
    for names in callers.values():
        for name in names:
            if name.startswith(DIRECT_PREFIX):
                client[name] = ("GET", name.removeprefix(DIRECT_PREFIX))
    return routes, callers, client


class Routes(Extractor):
    name = "routes"
    header = HEADER
    columns = ["route", "methods", "router", "uses", "called by"]

    def items(self) -> list[Item]:
        routes, callers, client = _dashboard()
        by_endpoint: dict[tuple[str, str], list[str]] = defaultdict(list)
        for name, (method, path) in client.items():
            by_endpoint[(method, _normalise(path))].append(name)
        out = []
        for path in sorted(routes):
            route = routes[path]
            short = path.removeprefix(API_PREFIX)
            methods = sorted(route.methods - {"HEAD"})
            functions = {n for m in methods for n in by_endpoint.get((m, _normalise(short)), [])}
            called_by = sorted(c for c, names in callers.items() if set(names) & functions)
            uses = group_calls(route.uses)
            row = [
                f"`{short}`",
                " ".join(methods),
                f"`{route.router}`",
                "; ".join(uses) or "-",
                ", ".join(f"`{c}`" for c in called_by) or "-",
            ]
            out.append(
                Item(f"route:{short}", [*methods, route.router, *uses, "callers:", *called_by], row)
            )
        self.caches = _caches()
        out += [Item(f"cache:{row[0].strip('`')}", row[1:], row) for row in self.caches]
        return out

    def render(self, items, gaps):
        routes = [item.row for item in items if item.kind == "route"]
        return (
            "# HTTP routes and caches\n\nEvery route, all under `/api`. *Uses* is what the "
            "endpoint reaches through optscan imports, following helper functions in the same "
            "router; *called by* is every dashboard file whose client calls hit it.\n\n"
            + table(self.columns, routes)
            + "\n## Caches in `api/deps.py`\n\nEach `_TimedCache`, the TTL constants used where "
            "it is filled, and the functions that clear it.\n\n"
            + table(["cache", "capacity", "TTL", "filled in", "cleared by"], self.caches)
        )


class Views(Extractor):
    name = "views"
    header = HEADER

    def items(self) -> list[Item]:
        _, callers, client = _dashboard()
        out = []
        for caller in sorted(callers):
            names = callers[caller]
            hits = [f"`{n}` ({' '.join(client[n])})" if n in client else f"`{n}`" for n in names]
            facts = [f"{n} {' '.join(client.get(n, ('?', '?')))}" for n in names]
            row = [f"`{caller}`", ", ".join(hits) or "none (composes other views)"]
            out.append(Item(f"view:{caller}", facts, row))
        return out

    def gaps(self) -> dict[str, list[str]]:
        routes, _, client = _dashboard()
        route_keys = {
            (method, _normalise(path.removeprefix(API_PREFIX)))
            for path, route in routes.items()
            for method in route.methods
        }
        return {
            "Client calls that match no route": sorted(
                f"`api.{name}` -> {method} `{path}`"
                for name, (method, path) in client.items()
                if (method, _normalise(path)) not in route_keys
            )
        }

    def render(self, items, gaps):
        _, callers, client = _dashboard()
        called = {name for names in callers.values() for name in names}
        unused = sorted(f"`api.{name}`" for name in client if name not in called)
        unmatched = gaps["Client calls that match no route"]
        return (
            "# Dashboard views\n\nEvery file under `frontend/src/views`, and any other frontend "
            "file that calls the API client (`frontend/src/api.js`, the only HTTP client), "
            "with the client functions it calls and their method and path.\n\n"
            + table(["file", "calls"], [item.row for item in items])
            + "\n## Client calls that match no route\n\n"
            + ("\n".join(f"- {line}" for line in unmatched) or "None.")
            + "\n\n## Client functions no file calls\n\n"
            + (", ".join(unused) or "None.")
            + "\n"
        )


# ---- schedule and commands ----------------------------------------------------------


class Schedule(Extractor):
    name = "schedule"
    header = HEADER
    title = "Scheduled jobs"
    intro = (
        "From `jobs/schedule.py` `jobs()`, at the shipped default times (market time). The "
        "user installs them with `optscan schedule --install`."
    )
    columns = ["job", "at", "repeats", "default install", "trading days only", "runs"]

    def items(self) -> list[Item]:
        # model_construct takes the declared defaults and reads no environment, so the times
        # here are the shipped ones on every machine, not whatever this one overrides.
        settings = Settings.model_construct()
        out = []
        for job in jobs(settings):
            repeats = (
                f"every {job.repeat_minutes} min for {job.repeat_for_minutes} min"
                if job.repeat_minutes
                else "once"
            )
            runs = "optscan " + job.arguments.removeprefix("-m optscan ").strip()
            facts = [
                job.at.strftime("%H:%M"),
                repeats,
                f"default install {job.default_install}",
                f"trading days only {job.trading_days_only}",
                runs,
            ]
            row = [
                f"`{job.key}`",
                facts[0],
                repeats,
                "yes" if job.default_install else "no",
                "yes" if job.trading_days_only else "no",
                f"`{runs}`",
            ]
            out.append(Item(f"job:{job.key}", facts, row))
        return out


class Commands(Extractor):
    name = "commands"
    header = HEADER
    title = "Commands"
    intro = (
        "Every `optscan` command, its handler in `cli.py`, and the modules the handler imports "
        "(following the helpers it calls in `cli.py`)."
    )
    columns = ["command", "handler", "imports"]

    def items(self) -> list[Item]:
        tree = ast.parse((SRC / "cli.py").read_text(encoding="utf-8"))
        main = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "main")
        handlers = next(
            node.value
            for node in ast.walk(main)
            if isinstance(node, ast.Assign)
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == "handlers"
        )
        functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
        out = []
        for key, value in zip(handlers.keys, handlers.values, strict=True):
            command, handler = key.value, value.id
            modules, seen, queue = set(), {handler}, [handler]
            while queue:
                function = functions[queue.pop()]
                for node in ast.walk(function):
                    if isinstance(node, ast.ImportFrom) and node.module:
                        if node.module.startswith("optscan") and not node.module.startswith(
                            QUIET_IMPORTS
                        ):
                            for alias in node.names:
                                path = IMPORTS.module_path(f"{node.module}.{alias.name}")
                                modules.add(path or IMPORTS.module_path(node.module) or node.module)
                    elif (
                        isinstance(node, ast.Name) and node.id in functions and node.id not in seen
                    ):
                        seen.add(node.id)
                        queue.append(node.id)
            found = sorted(modules)
            row = [f"`{command}`", f"`{handler}`", ", ".join(f"`{m}`" for m in found) or "-"]
            out.append(Item(f"command:{command}", [handler, *found], row))
        return sorted(out, key=lambda item: item.row)


def extractors() -> list[Extractor]:
    return [Modules(), Storage(), Routes(), Views(), Schedule(), Commands()]
