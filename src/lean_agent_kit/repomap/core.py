"""The map's core: items, fact hashes, notes, stamping, checks and the Markdown writer.

Every fact in `map/generated/` is extracted from the code by an `Extractor`, never typed.
`check` regenerates in memory and fails on any difference, so a committed fact cannot
disagree with the code.

What a machine cannot know (why a table exists, what a lookup has cost before) lives in
`map/notes.md`, one entry per item, pinned to a hash of that item's facts. The hash is
taken over the item's wiring, not its file: an unrelated edit leaves its notes alone,
while a new writer or a dropped reader changes the hash, and the note fails until someone
re-reads it and runs `lean-agents map stamp <key>`.

Nothing here knows any particular stack; extractors do.
"""

from __future__ import annotations

import hashlib
import re
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

HEADER = (
    "<!-- Generated by `lean-agents map generate` from the code. Do not edit by hand: "
    "`lean-agents map check` fails on any difference. -->\n\n"
)


def fact_hash(facts: list[str]) -> str:
    """A short hash of an item's facts: what a note is pinned to."""
    return hashlib.sha256("\n".join(facts).encode("utf-8")).hexdigest()[:12]


@dataclass
class Item:
    """One thing on the map, named the way notes name it: `table:daily_condition`.

    `facts` are what the note is pinned to; `row` is the item's line in the generated
    table (the extractor's `columns`), and `group` the `## ` subsection it sits under.
    """

    key: str
    facts: list[str]
    row: list[str] = field(default_factory=list)
    group: str = ""

    @property
    def kind(self) -> str:
        return self.key.split(":", 1)[0]

    @property
    def name(self) -> str:
        return self.key.split(":", 1)[-1]

    @property
    def fact_hash(self) -> str:
        return fact_hash(self.facts)


class Extractor:
    """One generated file. Subclass it and implement `items`.

    `name` is the file (`map/generated/<name>.md`), `title` and `intro` head it, and
    `columns` head its table. `gaps` lists what the extractor saw but could not resolve
    (a table name built at run time, a call that matches no route); `check` fails when
    there are more than `gap_budget`, since an incomplete scan should not look complete.
    """

    name = ""
    header = HEADER
    title = ""
    intro = ""
    columns: list[str] = []
    gap_budget = 0

    def items(self) -> list[Item]:
        raise NotImplementedError

    def gaps(self) -> dict[str, list[str]]:
        """Heading -> unresolved lines. Each heading is written even when empty."""
        return {}

    def render(self, items: list[Item], gaps: dict[str, list[str]]) -> str:
        """The file's Markdown, after `HEADER`. Override for a layout the tables do not fit."""
        return render(self, items, gaps)


@dataclass
class RepoMap:
    """Generated files by name, items by key, and the gaps over their extractor's budget."""

    files: dict[str, str]
    items: dict[str, Item]
    gaps: dict[str, list[str]] = field(default_factory=dict)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip() or "-"


def table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def render(extractor: Extractor, items: list[Item], gaps: dict[str, list[str]]) -> str:
    """The default Markdown for an extractor: title, intro, one table per group, gaps."""
    parts = [f"# {extractor.title}\n\n{extractor.intro.strip()}\n"]
    groups: dict[str, list[Item]] = {}
    for item in items:
        groups.setdefault(item.group, []).append(item)
    for group in sorted(groups):
        rows = [item.row or [f"`{item.name}`", *item.facts] for item in groups[group]]
        heading = f"\n## {group}\n" if group else ""
        parts.append(f"{heading}\n" + table(extractor.columns, rows))
    for heading, lines in gaps.items():
        parts.append(f"\n## {heading}\n\n" + ("\n".join(f"- {x}" for x in lines) or "None.") + "\n")
    return "".join(parts)


def generate(extractors: list[Extractor]) -> RepoMap:
    """Build every generated file and item from the code, in memory."""
    out = RepoMap(files={}, items={})
    for extractor in extractors:
        items = extractor.items()
        gaps = extractor.gaps()
        for item in items:
            if item.key in out.items:
                raise ValueError(f"two extractors produce {item.key}")
            out.items[item.key] = item
        over = sum(len(lines) for lines in gaps.values()) > extractor.gap_budget
        for heading, lines in gaps.items():
            if over and lines:
                out.gaps[f"{extractor.name}: {heading}"] = lines
        out.files[f"{extractor.name}.md"] = extractor.header + extractor.render(items, gaps)
    out.files = dict(sorted(out.files.items()))
    return out


def stale_files(repo_map: RepoMap, generated: Path) -> list[str]:
    """Generated files that differ from the code, are missing, or should not exist."""
    stale = [
        name
        for name, text in repo_map.files.items()
        if not (generated / name).exists()
        or (generated / name).read_text(encoding="utf-8") != text
    ]
    stray = [p.name for p in generated.glob("*.md") if p.name not in repo_map.files]
    return sorted(stale + stray)


def write(repo_map: RepoMap, generated: Path) -> list[str]:
    """Write the generated files; returns the names that changed."""
    generated.mkdir(parents=True, exist_ok=True)
    changed = stale_files(repo_map, generated)
    for name in changed:
        if name in repo_map.files:
            (generated / name).write_text(repo_map.files[name], encoding="utf-8", newline="\n")
        else:
            (generated / name).unlink()
    return changed


# ---- notes --------------------------------------------------------------------------


@dataclass
class Note:
    key: str
    fact: str | None
    test: str | None
    body: str


_NOTE_HEAD = re.compile(r"^### (\S+)[ \t]*$", re.M)


def load_notes(text: str) -> list[Note]:
    """Parse notes: `### key`, then `fact: <hash>` or `test: <file>::<name>`."""
    heads = list(_NOTE_HEAD.finditer(text))
    notes = []
    for index, head in enumerate(heads):
        end = heads[index + 1].start() if index + 1 < len(heads) else len(text)
        block = text[head.end() : end]
        fact = re.search(r"^fact: (\w+)\s*$", block, re.M)
        test = re.search(r"^test: (\S+)\s*$", block, re.M)
        notes.append(
            Note(
                key=head.group(1),
                fact=fact.group(1) if fact else None,
                test=test.group(1) if test else None,
                body=textwrap.dedent(block).strip(),
            )
        )
    return notes


def stamp(text: str, keys: list[str], repo_map: RepoMap, *, every: bool = False) -> tuple[str, list[str]]:
    """Set the fact hash of the named notes (or all) to the current one: (new text, keys)."""
    stamped = []
    for note in load_notes(text):
        if not (every or note.key in keys) or note.key not in repo_map.items:
            continue
        current = repo_map.items[note.key].fact_hash
        if note.fact == current:
            continue
        heading = f"### {note.key}\n"
        at = text.index(heading) + len(heading)
        following = _NOTE_HEAD.search(text, at)
        end = following.start() if following else len(text)
        block = text[at:end]
        if re.search(r"^fact:", block, re.M):
            block = re.sub(r"^fact:[^\n]*$", f"fact: {current}", block, count=1, flags=re.M)
        else:
            block = f"fact: {current}\n" + block
        text = text[:at] + block + text[end:]
        stamped.append(note.key)
    return text, stamped


def problems(
    repo_map: RepoMap, notes: list[Note], required: tuple[str, ...] = ("table", "job")
) -> dict[str, list[str]]:
    """Everything wrong with the notes, by check. `required` kinds must each have a note."""
    items = repo_map.items
    keyed = {note.key: note for note in notes}
    return {
        "missing": sorted(
            key for key, item in items.items() if item.kind in required and key not in keyed
        ),
        "dead": sorted(note.key for note in notes if note.test is None and note.key not in items),
        "stale": sorted(
            note.key
            for note in notes
            if note.key in items and note.fact != items[note.key].fact_hash
        ),
        "unpinned": sorted(note.key for note in notes if note.fact is None and note.test is None),
    }


def broken_traps(notes: list[Note], root: Path) -> list[str]:
    """`trap:` notes whose `test: <file>::<name>` names no such test function."""
    broken = []
    for note in notes:
        if not note.key.startswith("trap:") or note.test == "none":
            continue
        if not note.test:
            broken.append(f"{note.key} -> (no test: line)")
            continue
        file, _, name = note.test.partition("::")
        path = root / file
        if not path.is_file() or not re.search(
            rf"^\s*(?:async\s+)?def {re.escape(name)}\(", path.read_text(encoding="utf-8"), re.M
        ):
            broken.append(f"{note.key} -> {note.test}")
    return broken
